CREATE OR REPLACE FUNCTION public.create_institutional_event_reservation(
  p_user_id bigint,
  p_activity_name text,
  p_outside_participants boolean,
  p_proof_of_consent_url text,
  p_venues jsonb,
  p_equipment jsonb
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, private, auth
AS $$
DECLARE
  current_user_id bigint := private.current_profile_id();
  requester_role text;
  requester_program_id bigint;
  event_dean_role text;
  event_dean_office_id bigint;
  created_reservation_id bigint;
  first_date date;
  first_start timestamp without time zone;
  last_end timestamp without time zone;
  room_record record;
  venue_record record;
  equipment_record record;
  venue_ids bigint[] := ARRAY[]::bigint[];
  venue_id bigint;
  room_link_id bigint;
  item_link_id bigint;
  chosen_unit_ids bigint[];
  item_count integer;
  step_index integer := 0;
  office_id bigint;
  office_name text;
  office_names text[] := ARRAY[]::text[];
  office_ids bigint[] := ARRAY[]::bigint[];
  is_program_chair_request boolean;
  contains_gym boolean := false;
BEGIN
  IF auth.uid() IS NULL
     OR current_user_id IS NULL
     OR p_user_id IS DISTINCT FROM current_user_id THEN
    RAISE EXCEPTION 'Sign in as the requesting account before submitting.'
      USING ERRCODE = '42501';
  END IF;

  SELECT lower(profile.role), profile.program_id
  INTO requester_role, requester_program_id
  FROM public.users AS profile
  WHERE profile.user_id = current_user_id
    AND profile.is_active;

  is_program_chair_request := private.is_program_chair_profile(current_user_id);
  IF NOT is_program_chair_request
     AND NOT private.is_dean_profile(current_user_id) THEN
    RAISE EXCEPTION 'Institutional Event requests are available to active Program Chairs and Deans.'
      USING ERRCODE = '42501';
  END IF;

  IF coalesce(trim(p_activity_name), '') = ''
     OR length(trim(p_activity_name)) > 200 THEN
    RAISE EXCEPTION 'Enter an event name of 1 to 200 characters.'
      USING ERRCODE = '22023';
  END IF;

  IF p_venues IS NULL
     OR jsonb_typeof(p_venues) IS DISTINCT FROM 'array'
     OR jsonb_array_length(p_venues) = 0
     OR jsonb_array_length(p_venues) > 30 THEN
    RAISE EXCEPTION 'Select between 1 and 30 venues.'
      USING ERRCODE = '22023';
  END IF;

  IF (
    SELECT count(*) <> count(DISTINCT value ->> 'room_id')
    FROM jsonb_array_elements(p_venues)
  ) THEN
    RAISE EXCEPTION 'A venue can only be selected once per event.'
      USING ERRCODE = '22023';
  END IF;

  IF jsonb_typeof(coalesce(p_equipment, '[]'::jsonb)) <> 'array' THEN
    RAISE EXCEPTION 'Equipment selection must be a list.'
      USING ERRCODE = '22023';
  END IF;

  FOR room_record IN
    SELECT DISTINCT (venue.value ->> 'room_id')::bigint AS room_id
    FROM jsonb_array_elements(p_venues) AS venue(value)
    ORDER BY room_id
  LOOP
    PERFORM 1 FROM public.rooms
    WHERE room_id = room_record.room_id
    FOR UPDATE;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'One of the selected venues no longer exists.'
        USING ERRCODE = '22023';
    END IF;
  END LOOP;

  FOR venue_record IN
    SELECT value
    FROM jsonb_array_elements(p_venues)
  LOOP
    IF NOT (venue_record.value ? 'room_id')
       OR NOT (venue_record.value ? 'start_time')
       OR NOT (venue_record.value ? 'end_time') THEN
      RAISE EXCEPTION 'Each venue needs a room and a schedule.'
        USING ERRCODE = '22023';
    END IF;

    IF (venue_record.value ->> 'end_time')::timestamp
         <= (venue_record.value ->> 'start_time')::timestamp
       OR (venue_record.value ->> 'start_time')::date
         <> (venue_record.value ->> 'end_time')::date
       OR (venue_record.value ->> 'start_time')::date < current_date + 3 THEN
      RAISE EXCEPTION 'Each venue needs a valid same-day schedule at least two days in advance.'
        USING ERRCODE = '22023';
    END IF;

    IF EXISTS (
      SELECT 1
      FROM public.institutional_event_venues AS event_venue
      JOIN public.reservations AS existing_reservation
        ON existing_reservation.reservation_id = event_venue.reservation_id
      WHERE event_venue.room_id = (venue_record.value ->> 'room_id')::bigint
        AND event_venue.status = 'included'
        AND event_venue.start_time < (venue_record.value ->> 'end_time')::timestamp
        AND event_venue.end_time > (venue_record.value ->> 'start_time')::timestamp
        AND NOT (lower(coalesce(existing_reservation.overall_status, '')) LIKE
          ANY (ARRAY['%cancelled%', '%canceled%', '%rejected%', '%denied%',
                     '%timed out%', '%returned%', '%void%']))
    ) OR EXISTS (
      SELECT 1
      FROM public.reservation_rooms AS existing_room
      JOIN public.reservations AS existing_reservation
        ON existing_reservation.reservation_id = existing_room.reservation_id
      WHERE existing_room.room_id = (venue_record.value ->> 'room_id')::bigint
        AND NOT EXISTS (
          SELECT 1 FROM public.institutional_event_venues AS event_venue
          WHERE event_venue.reservation_id = existing_reservation.reservation_id
        )
        AND existing_reservation."Start_of_activity" <
          (venue_record.value ->> 'end_time')::timestamp
        AND existing_reservation."End_of_Activity" >
          (venue_record.value ->> 'start_time')::timestamp
        AND NOT (lower(coalesce(existing_reservation.overall_status, '')) LIKE
          ANY (ARRAY['%cancelled%', '%canceled%', '%rejected%', '%denied%',
                     '%timed out%', '%returned%', '%void%']))
    ) THEN
      RAISE EXCEPTION 'Venue % is no longer available at the selected time.',
        venue_record.value ->> 'room_id'
        USING ERRCODE = '23P01';
    END IF;

    IF first_date IS NULL
       OR (venue_record.value ->> 'start_time')::date < first_date THEN
      first_date := (venue_record.value ->> 'start_time')::date;
    END IF;
    IF first_start IS NULL
       OR (venue_record.value ->> 'start_time')::timestamp < first_start THEN
      first_start := (venue_record.value ->> 'start_time')::timestamp;
    END IF;
    IF last_end IS NULL
       OR (venue_record.value ->> 'end_time')::timestamp > last_end THEN
      last_end := (venue_record.value ->> 'end_time')::timestamp;
    END IF;
  END LOOP;

  IF is_program_chair_request THEN
    SELECT assignment.dean_role, dean_office.office_id
    INTO event_dean_role, event_dean_office_id
    FROM public.dean_program_assignments AS assignment
    JOIN public.dean_role_offices AS dean_office
      ON dean_office.dean_role = assignment.dean_role
    WHERE assignment.program_id = requester_program_id;
    IF event_dean_office_id IS NULL THEN
      RAISE EXCEPTION 'No Dean is configured for your assigned program.'
        USING ERRCODE = '22023';
    END IF;
  END IF;

  SELECT coalesce(bool_or(lower(room.room_type) LIKE '%gym%'), false)
  INTO contains_gym
  FROM jsonb_array_elements(p_venues) AS requested_venue
  JOIN public.rooms AS room
    ON room.room_id = (requested_venue.value ->> 'room_id')::bigint;

  IF contains_gym THEN
    SELECT office.office_id INTO office_id
    FROM public.offices AS office
    WHERE lower(office.department_name) = 'general education'
       OR lower(office.short_code) = 'general_education'
    ORDER BY CASE WHEN lower(office.department_name) = 'general education'
      THEN 0 ELSE 1 END
    LIMIT 1;
    IF office_id IS NULL THEN
      RAISE EXCEPTION 'General Education approval office is not configured.'
        USING ERRCODE = '22023';
    END IF;
    office_ids := array_append(office_ids, office_id);
    office_names := array_append(office_names, 'General Education');
  END IF;

  IF is_program_chair_request THEN
    office_ids := array_append(office_ids, event_dean_office_id);
    office_names := array_append(office_names, 'Dean');
  END IF;

  FOR office_name IN
    SELECT unnest(ARRAY['SDAO', 'DO', 'Security', 'Physical Facilities'])
  LOOP
    SELECT office.office_id INTO office_id
    FROM public.offices AS office
    WHERE lower(office.department_name) = lower(office_name)
       OR (office_name = 'DO' AND lower(office.short_code) = 'do')
    ORDER BY CASE
      WHEN lower(office.department_name) = lower(office_name) THEN 0
      ELSE 1
    END
    LIMIT 1;
    IF office_id IS NULL THEN
      RAISE EXCEPTION 'Required approval office % is not configured.', office_name
        USING ERRCODE = '22023';
    END IF;
    office_ids := array_append(office_ids, office_id);
    office_names := array_append(office_names, office_name);
  END LOOP;

  INSERT INTO public.reservations (
    user_id, activity_name, overall_status, "Date_of_Activity",
    "Start_of_activity", "End_of_Activity", outside_participants,
    proof_of_consent_url, created_at, updated_at
  )
  VALUES (
    current_user_id, trim(p_activity_name), 'Pending Approval',
    first_date::timestamp, first_start, last_end, coalesce(p_outside_participants, false),
    p_proof_of_consent_url, now(), now()
  )
  RETURNING reservation_id INTO created_reservation_id;

  INSERT INTO public.institutional_event_requests (reservation_id)
  VALUES (created_reservation_id);

  FOR venue_record IN
    SELECT value
    FROM jsonb_array_elements(p_venues)
  LOOP
    INSERT INTO public.reservation_rooms (
      reservation_id, room_id, created_at, updated_at
    )
    VALUES (
      created_reservation_id,
      (venue_record.value ->> 'room_id')::bigint,
      now(), now()
    )
    RETURNING reservation_rooms_id INTO room_link_id;

    INSERT INTO public.reservation_details (
      reservation_id, reservation_rooms_id, quantity, created_at, updated_at
    )
    VALUES (created_reservation_id, room_link_id, 1, now(), now());

    INSERT INTO public.institutional_event_venues (
      reservation_id, room_id, activity_date, start_time, end_time
    )
    VALUES (
      created_reservation_id,
      (venue_record.value ->> 'room_id')::bigint,
      (venue_record.value ->> 'start_time')::timestamp::date,
      (venue_record.value ->> 'start_time')::timestamp,
      (venue_record.value ->> 'end_time')::timestamp
    )
    RETURNING event_venue_id INTO venue_id;
    venue_ids := array_append(venue_ids, venue_id);
  END LOOP;

  IF jsonb_array_length(coalesce(p_equipment, '[]'::jsonb)) > 0 THEN
    FOR equipment_record IN
      SELECT value
      FROM jsonb_array_elements(p_equipment)
    LOOP
      IF coalesce((equipment_record.value ->> 'quantity')::integer, 0) <= 0
         OR coalesce((equipment_record.value ->> 'venue_index')::integer, -1)
           < 0
         OR coalesce((equipment_record.value ->> 'venue_index')::integer, -1)
           >= cardinality(venue_ids) THEN
        RAISE EXCEPTION 'Each equipment item needs a positive quantity and a selected venue.'
          USING ERRCODE = '22023';
      END IF;

      venue_id := venue_ids[
        (equipment_record.value ->> 'venue_index')::integer + 1
      ];
      item_count := (equipment_record.value ->> 'quantity')::integer;

      INSERT INTO public.reservation_items (
        reservation_id, item_id, created_at, updated_at
      )
      VALUES (
        created_reservation_id,
        (equipment_record.value ->> 'item_id')::bigint,
        now(), now()
      )
      RETURNING reservation_items_id INTO item_link_id;

      INSERT INTO public.reservation_details (
        reservation_id, reservation_items_id, quantity, created_at, updated_at
      )
      VALUES (created_reservation_id, item_link_id, item_count, now(), now());

      INSERT INTO public.institutional_event_equipment (
        reservation_id, event_venue_id, reservation_items_id
      )
      VALUES (created_reservation_id, venue_id, item_link_id);

      SELECT coalesce(array_agg(available_unit.unit_id), ARRAY[]::bigint[])
      INTO chosen_unit_ids
      FROM (
        SELECT unit.unit_id
        FROM public.item_units AS unit
        WHERE unit.item_id = (equipment_record.value ->> 'item_id')::bigint
          AND lower(trim(coalesce(unit.status, ''))) IN
            ('available', 'free', 'ready', 'active', 'new', 'in_stock', 'instock')
          AND NOT EXISTS (
            SELECT 1
            FROM public.reservation_item_units AS held
            JOIN public.reservation_items AS held_item
              ON held_item.reservation_items_id = held.reservation_items_id
            JOIN public.reservations AS held_reservation
              ON held_reservation.reservation_id = held_item.reservation_id
            LEFT JOIN public.institutional_event_equipment AS held_equipment
              ON held_equipment.reservation_items_id =
                 held_item.reservation_items_id
            LEFT JOIN public.institutional_event_venues AS held_venue
              ON held_venue.event_venue_id = held_equipment.event_venue_id
            WHERE held.unit_id = unit.unit_id
              AND NOT (lower(coalesce(held_reservation.overall_status, ''))
                LIKE ANY (ARRAY['%cancelled%', '%canceled%', '%rejected%',
                  '%denied%', '%timed out%', '%returned%', '%void%']))
              AND (
                (
                  held_equipment.event_equipment_id IS NOT NULL
                  AND held_equipment.status = 'included'
                  AND held_venue.status = 'included'
                  AND held_venue.start_time <
                    (SELECT requested_venue.end_time
                     FROM public.institutional_event_venues AS requested_venue
                     WHERE requested_venue.event_venue_id = venue_id)
                  AND held_venue.end_time >
                    (SELECT requested_venue.start_time
                     FROM public.institutional_event_venues AS requested_venue
                     WHERE requested_venue.event_venue_id = venue_id)
                )
                OR (
                  held_equipment.event_equipment_id IS NULL
                  AND held_reservation."Start_of_activity" <
                    (SELECT requested_venue.end_time
                     FROM public.institutional_event_venues AS requested_venue
                     WHERE requested_venue.event_venue_id = venue_id)
                  AND held_reservation."End_of_Activity" >
                    (SELECT requested_venue.start_time
                     FROM public.institutional_event_venues AS requested_venue
                     WHERE requested_venue.event_venue_id = venue_id)
                )
              )
          )
        ORDER BY unit.unit_id
        LIMIT item_count
        FOR UPDATE SKIP LOCKED
      ) AS available_unit;

      IF cardinality(chosen_unit_ids) < item_count THEN
        RAISE EXCEPTION 'Not enough available units for item % at its linked venue.',
          equipment_record.value ->> 'item_id'
          USING ERRCODE = '23P01';
      END IF;

      INSERT INTO public.reservation_item_units (
        reservation_items_id, unit_id, created_at, updated_at
      )
      SELECT item_link_id, chosen_unit_id, now(), now()
      FROM unnest(chosen_unit_ids) AS chosen_unit_id;

      UPDATE public.item_units
      SET status = 'in_use', updated_at = now()
      WHERE unit_id = ANY(chosen_unit_ids);
    END LOOP;
  END IF;

  FOREACH office_id IN ARRAY office_ids
  LOOP
    step_index := step_index + 1;
    INSERT INTO public.reservation_approvals (
      reservation_id, office_id, approval_stage, status, created_at, updated_at
    )
    VALUES (
      created_reservation_id,
      office_id,
      CASE WHEN is_program_chair_request
             AND office_id = event_dean_office_id
        THEN 'dean' ELSE 'office' END,
      CASE WHEN step_index = 1 THEN 'Pending' ELSE 'Waiting' END,
      now() + make_interval(secs => step_index),
      now() + make_interval(secs => step_index)
    );
  END LOOP;

  RETURN created_reservation_id;
END;
$$;

