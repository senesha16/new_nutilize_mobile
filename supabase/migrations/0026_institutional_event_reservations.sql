) TO authenticated, service_role;

CREATE OR REPLACE FUNCTION public.respond_to_institutional_event_approval(
  p_approval_id bigint,
  p_decision text,
  p_message text DEFAULT NULL,
  p_rejection_reason text DEFAULT NULL,
  p_removed_venue_ids bigint[] DEFAULT ARRAY[]::bigint[],
  p_removed_equipment_ids bigint[] DEFAULT ARRAY[]::bigint[]
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, private, auth
AS $$
DECLARE
  current_user_id bigint := private.current_profile_id();
  target_reservation_id bigint;
  normalized_decision text := lower(trim(coalesce(p_decision, '')));
  reason text := trim(coalesce(p_rejection_reason, ''));
  selected_venue_ids bigint[] := coalesce(p_removed_venue_ids, ARRAY[]::bigint[]);
  selected_equipment_ids bigint[] :=
    coalesce(p_removed_equipment_ids, ARRAY[]::bigint[]);
  changed_count integer;
  remaining_venue_count integer;
BEGIN
  IF auth.uid() IS NULL
     OR current_user_id IS NULL
     OR (
       NOT private.is_program_chair_profile(current_user_id)
       AND NOT private.is_dean_profile(current_user_id)
     ) THEN
    RAISE EXCEPTION 'Only an active Program Chair or Dean may review an event request.'
      USING ERRCODE = '42501';
  END IF;

  IF normalized_decision NOT IN ('approve', 'reject', 'reconsider') THEN
    RAISE EXCEPTION 'Decision must be approve, reject, or reconsider.'
      USING ERRCODE = '22023';
  END IF;

  SELECT reservation.reservation_id
  INTO target_reservation_id
  FROM public.reservation_approvals AS approval
  JOIN public.reservations AS reservation
    ON reservation.reservation_id = approval.reservation_id
  JOIN public.institutional_event_requests AS event_request
    ON event_request.reservation_id = reservation.reservation_id
  WHERE approval.approval_id = p_approval_id;

  IF target_reservation_id IS NULL THEN
    RAISE EXCEPTION 'This Institutional Event approval does not exist.'
      USING ERRCODE = '42501';
  END IF;

  PERFORM 1
  FROM public.reservations AS reservation
  WHERE reservation.reservation_id = target_reservation_id
  FOR UPDATE;

  IF cardinality(selected_venue_ids) > 0
     OR cardinality(selected_equipment_ids) > 0 THEN
    IF normalized_decision <> 'approve'
       OR reason = ''
       OR length(reason) > 500 THEN
      RAISE EXCEPTION 'Removing resources requires approval and a reason of up to 500 characters.'
        USING ERRCODE = '22023';
    END IF;

    IF cardinality(selected_venue_ids) <>
       (SELECT count(DISTINCT requested.requested_id)
        FROM unnest(selected_venue_ids) AS requested(requested_id)) THEN
      RAISE EXCEPTION 'A venue may only be selected once.'
        USING ERRCODE = '22023';
    END IF;

    IF cardinality(selected_equipment_ids) <>
       (SELECT count(DISTINCT requested.requested_id)
        FROM unnest(selected_equipment_ids) AS requested(requested_id)) THEN
      RAISE EXCEPTION 'An equipment resource may only be selected once.'
        USING ERRCODE = '22023';
    END IF;

    UPDATE public.institutional_event_venues
    SET status = 'removed', removal_reason = reason
    WHERE reservation_id = target_reservation_id
      AND event_venue_id = ANY(selected_venue_ids)
      AND status = 'included';
    GET DIAGNOSTICS changed_count = ROW_COUNT;
    IF changed_count <> cardinality(selected_venue_ids) THEN
      RAISE EXCEPTION 'One or more selected venues are not part of this active event.'
        USING ERRCODE = '22023';
    END IF;

    SELECT count(*) INTO changed_count
    FROM public.institutional_event_equipment
    WHERE reservation_id = target_reservation_id
      AND event_equipment_id = ANY(selected_equipment_ids)
      AND status = 'included';
    IF changed_count <> cardinality(selected_equipment_ids) THEN
      RAISE EXCEPTION 'One or more selected equipment resources are not part of this active event.'
        USING ERRCODE = '22023';
    END IF;

    UPDATE public.institutional_event_equipment AS equipment
    SET status = 'removed', removal_reason = reason
    WHERE equipment.reservation_id = target_reservation_id
      AND equipment.status = 'included'
      AND (
        equipment.event_equipment_id = ANY(selected_equipment_ids)
        OR equipment.event_venue_id = ANY(selected_venue_ids)
      );

    SELECT count(*) INTO remaining_venue_count
    FROM public.institutional_event_venues
    WHERE reservation_id = target_reservation_id
      AND status = 'included';
    IF remaining_venue_count = 0 THEN
      RAISE EXCEPTION 'At least one venue must remain. Reject the whole event if no venues can be approved.'
        USING ERRCODE = '22023';
    END IF;

    UPDATE public.item_units AS unit
    SET status = 'available', updated_at = now()
    FROM public.reservation_item_units AS held
    JOIN public.institutional_event_equipment AS equipment
      ON equipment.reservation_items_id = held.reservation_items_id
    WHERE equipment.reservation_id = target_reservation_id
      AND equipment.status = 'removed'
      AND (
        equipment.event_equipment_id = ANY(selected_equipment_ids)
        OR equipment.event_venue_id = ANY(selected_venue_ids)
      )
      AND unit.unit_id = held.unit_id;

    DELETE FROM public.reservation_item_units AS held
    USING public.institutional_event_equipment AS equipment
    WHERE equipment.reservation_id = target_reservation_id
      AND equipment.status = 'removed'
      AND equipment.reservation_items_id = held.reservation_items_id
      AND (
        equipment.event_equipment_id = ANY(selected_equipment_ids)
        OR equipment.event_venue_id = ANY(selected_venue_ids)
      );

    UPDATE public.items AS item
    SET quantity_in_use = (
      SELECT count(*) FILTER (
        WHERE lower(trim(coalesce(unit.status, ''))) NOT IN
          ('available', 'free', 'ready', 'active', 'new', 'in_stock', 'instock')
      )::integer
      FROM public.item_units AS unit
      WHERE unit.item_id = item.item_id
    ),
    updated_at = now()
    WHERE item.item_id IN (
      SELECT DISTINCT reservation_item.item_id
      FROM public.institutional_event_equipment AS equipment
      JOIN public.reservation_items AS reservation_item
        ON reservation_item.reservation_items_id =
           equipment.reservation_items_id
      WHERE equipment.reservation_id = target_reservation_id
        AND equipment.status = 'removed'
        AND (
          equipment.event_equipment_id = ANY(selected_equipment_ids)
          OR equipment.event_venue_id = ANY(selected_venue_ids)
        )
    );
  END IF;

  IF private.is_program_chair_profile(current_user_id) THEN
    PERFORM public.respond_to_program_chair_approval(
      p_approval_id, normalized_decision, p_message, p_rejection_reason
    );
  ELSE
    PERFORM public.respond_to_dean_approval(
      p_approval_id, normalized_decision, p_rejection_reason, p_message
    );
  END IF;

  RETURN true;
END;
$$;

REVOKE ALL ON FUNCTION public.respond_to_institutional_event_approval(
  bigint, text, text, text, bigint[], bigint[]
) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.respond_to_institutional_event_approval(
  bigint, text, text, text, bigint[], bigint[]
) TO authenticated, service_role;

COMMIT;
