CREATE TABLE IF NOT EXISTS public.institutional_event_requests (
  reservation_id bigint PRIMARY KEY
    REFERENCES public.reservations(reservation_id) ON DELETE CASCADE,
  created_at timestamp without time zone NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.institutional_event_venues (
  event_venue_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id bigint NOT NULL
    REFERENCES public.institutional_event_requests(reservation_id)
    ON DELETE CASCADE,
  room_id bigint NOT NULL REFERENCES public.rooms(room_id) ON DELETE RESTRICT,
  activity_date date NOT NULL,
  start_time timestamp without time zone NOT NULL,
  end_time timestamp without time zone NOT NULL,
  status text NOT NULL DEFAULT 'included'
    CHECK (status IN ('included', 'removed')),
  removal_reason text,
  created_at timestamp without time zone NOT NULL DEFAULT now(),
  CHECK (end_time > start_time),
  CHECK (activity_date = start_time::date AND activity_date = end_time::date),
  UNIQUE (reservation_id, room_id)
);

CREATE TABLE IF NOT EXISTS public.institutional_event_equipment (
  event_equipment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id bigint NOT NULL
    REFERENCES public.institutional_event_requests(reservation_id)
    ON DELETE CASCADE,
  event_venue_id bigint NOT NULL
    REFERENCES public.institutional_event_venues(event_venue_id)
    ON DELETE CASCADE,
  reservation_items_id bigint NOT NULL UNIQUE
    REFERENCES public.reservation_items(reservation_items_id)
    ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'included'
    CHECK (status IN ('included', 'removed')),
  removal_reason text,
  created_at timestamp without time zone NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS institutional_event_venues_room_schedule_idx
  ON public.institutional_event_venues (room_id, start_time, end_time)
  WHERE status = 'included';
CREATE INDEX IF NOT EXISTS institutional_event_equipment_reservation_idx
  ON public.institutional_event_equipment (reservation_id, event_venue_id)
  WHERE status = 'included';

ALTER TABLE public.institutional_event_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.institutional_event_venues ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.institutional_event_equipment ENABLE ROW LEVEL SECURITY;

